// platformOverview.js - the OPERATOR's read-only cross-tenant health/usage
// view (GET /api/platform/overview in routes/platformAdmin.js).
//
// READ THIS BEFORE CHANGING IT - it is the one place that deliberately reads
// across tenant schemas, against the isolation model in tenancy.js:
//
//   * AGGREGATES ONLY. Counts, sums, a latest timestamp. It never selects a
//     usage row, a key, a user name or any tenant content, so the response
//     cannot leak what one tenant did to another or to anyone but the operator.
//   * It does NOT go through tenancy.getTenantDb(). That function creates the
//     tenant's schema if it is missing (createSchemaLocked) - fine for serving
//     a live tenant, wrong for a read-only report: asking about a purged
//     tenant would silently resurrect an empty schema for it, and opening a
//     dedicated pool per tenant just to count rows would not scale to a list
//     of every tenant. Instead each tenant's own schema is read with a
//     schema-QUALIFIED table name over the control-plane connection. No
//     search_path is set or changed, so no connection state can carry from one
//     tenant to the next.
//   * The schema name is interpolated into SQL, so it is only ever taken from
//     the control-plane `tenants.schema_name` column (generated by the server,
//     never by a caller) AND re-validated against the same identifier rule
//     tenancy.js enforces before it is quoted in.
//   * Per-tenant failure is contained: a tenant whose schema is gone or whose
//     table is broken reports `usage: null` with a reason; it never fails the
//     whole report.
//   * Purely read-only: SELECTs only, nothing is written, no audit entry is
//     made. There is no operator identity behind FINOPS_PLATFORM_ADMIN_TOKEN
//     to attribute a read to (see routes/platformAdmin.js's header), which is
//     also why impersonation and internal notes are NOT built here.

const tenancy = require("./tenancy");
const { VALID_STATUSES } = require("./tenantLifecycle");
const { currentMonthBounds } = require("./storage/dialectSql");
const logger = require("./logger");

const DEFAULT_LIMIT = 200;
const MAX_LIMIT = 500;
const USAGE_CONCURRENCY = 4;
const QUOTA_NEAR_RATIO = 0.8;
const TRIAL_ENDING_SOON_MS = 7 * 24 * 60 * 60 * 1000;

const SAFE_SCHEMA_RE = /^[a-z_][a-z0-9_]*$/;

class OverviewInputError extends Error {
  constructor(message) {
    super(message);
    this.statusCode = 400;
  }
}

function parseOptions({ limit, status } = {}) {
  let parsedLimit = DEFAULT_LIMIT;
  if (limit !== undefined) {
    parsedLimit = Number(limit);
    if (!Number.isInteger(parsedLimit) || parsedLimit < 1 || parsedLimit > MAX_LIMIT) {
      throw new OverviewInputError(`limit must be an integer between 1 and ${MAX_LIMIT}`);
    }
  }
  if (status !== undefined && !VALID_STATUSES.includes(status)) {
    throw new OverviewInputError(`status must be one of: ${VALID_STATUSES.join(", ")}`);
  }
  return { limit: parsedLimit, status };
}

function flagsFor(tenant, usage, now) {
  const flags = [];
  const live = tenant.status === "active" || tenant.status === "trial";
  if (tenant.status === "trial" && tenant.trial_ends_at) {
    const ends = Date.parse(tenant.trial_ends_at);
    if (ends > now && ends - now <= TRIAL_ENDING_SOON_MS) flags.push("trial_ending_soon");
  }
  if (usage && tenant.max_monthly_events > 0) {
    if (usage.events_this_month >= tenant.max_monthly_events) flags.push("quota_exceeded");
    else if (usage.events_this_month >= tenant.max_monthly_events * QUOTA_NEAR_RATIO) flags.push("quota_near");
  }
  if (live && usage && usage.events_this_month === 0) flags.push("no_events_this_month");
  return flags;
}

// Aggregates for ONE tenant, read from its own schema. Never throws.
async function readUsage(controlPlaneDb, schemaName, bounds) {
  if (!SAFE_SCHEMA_RE.test(schemaName)) return { usage: null, reason: "error" };
  const table = `"${schemaName}".usage_events`;
  try {
    const month = await controlPlaneDb.get(
      `SELECT COUNT(*) AS events, COALESCE(SUM(cost_usd), 0) AS cost FROM ${table} WHERE event_time >= ? AND event_time < ?`,
      [bounds.start, bounds.end]
    );
    const last = await controlPlaneDb.get(`SELECT MAX(event_time) AS last_event_at FROM ${table}`);
    return {
      usage: {
        events_this_month: Number(month.events),
        cost_usd_this_month: Number(month.cost),
        last_event_at: last.last_event_at || null,
      },
    };
  } catch (err) {
    logger.warn("Platform overview: could not read a tenant's usage", { schema: schemaName, error: err.message });
    return { usage: null, reason: "error" };
  }
}

async function mapWithConcurrency(items, concurrency, fn) {
  const results = new Array(items.length);
  let next = 0;
  async function worker() {
    while (next < items.length) {
      const i = next++;
      results[i] = await fn(items[i], i);
    }
  }
  await Promise.all(Array.from({ length: Math.min(concurrency, items.length) }, worker));
  return results;
}

async function buildOverview(options) {
  const { limit, status } = parseOptions(options);
  const { controlPlaneReady, controlPlaneDb } = tenancy.initControlPlane();
  await controlPlaneReady;

  const byStatusRows = await controlPlaneDb.all("SELECT status, COUNT(*) AS n FROM tenants GROUP BY status");
  const tenantsByStatus = {};
  for (const row of byStatusRows) tenantsByStatus[row.status] = Number(row.n);

  const where = status ? " WHERE status = ?" : "";
  const matching = await controlPlaneDb.get(`SELECT COUNT(*) AS n FROM tenants${where}`, status ? [status] : []);
  const rows = await controlPlaneDb.all(
    `SELECT id, name, schema_name, status, created_at, trial_ends_at, purge_after, suspended_reason,
            max_api_keys, max_budgets, max_monthly_events
     FROM tenants${where} ORDER BY id LIMIT ?`,
    status ? [status, limit] : [limit]
  );

  const ids = rows.map((r) => r.id);
  const keyCounts = new Map();
  const userCounts = new Map();
  if (ids.length) {
    const marks = ids.map(() => "?").join(", ");
    for (const r of await controlPlaneDb.all(`SELECT tenant_id, COUNT(*) AS n FROM api_keys WHERE tenant_id IN (${marks}) GROUP BY tenant_id`, ids)) {
      keyCounts.set(r.tenant_id, Number(r.n));
    }
    for (const r of await controlPlaneDb.all(`SELECT tenant_id, COUNT(*) AS n FROM users WHERE tenant_id IN (${marks}) GROUP BY tenant_id`, ids)) {
      userCounts.set(r.tenant_id, Number(r.n));
    }
  }

  // Which of these tenants' schemas actually exist right now (a purged tenant's
  // does not) - one query, instead of discovering it by failing per tenant.
  const existing = new Set();
  const candidateSchemas = rows.filter((r) => r.status !== "deleted" && SAFE_SCHEMA_RE.test(r.schema_name)).map((r) => r.schema_name);
  if (candidateSchemas.length) {
    const found = await controlPlaneDb.all("SELECT schema_name FROM information_schema.schemata WHERE schema_name = ANY(?)", [candidateSchemas]);
    for (const r of found) existing.add(r.schema_name);
  }

  const bounds = currentMonthBounds();
  const usages = await mapWithConcurrency(rows, USAGE_CONCURRENCY, async (row) => {
    if (row.status === "deleted" || !existing.has(row.schema_name)) return { usage: null, reason: "schema_missing" };
    return readUsage(controlPlaneDb, row.schema_name, bounds);
  });

  const now = Date.now();
  let totalEvents = 0;
  let totalCost = 0;
  const tenants = rows.map((row, i) => {
    const { usage, reason } = usages[i];
    if (usage) {
      totalEvents += usage.events_this_month;
      totalCost += usage.cost_usd_this_month;
    }
    return {
      id: row.id,
      name: row.name,
      status: row.status,
      created_at: row.created_at,
      trial_ends_at: row.trial_ends_at || null,
      purge_after: row.purge_after || null,
      suspended_reason: row.suspended_reason || null,
      limits: { max_api_keys: row.max_api_keys, max_budgets: row.max_budgets, max_monthly_events: row.max_monthly_events },
      api_keys: keyCounts.get(row.id) || 0,
      users: userCounts.get(row.id) || 0,
      usage,
      usage_unavailable: usage ? null : reason,
      flags: flagsFor(row, usage, now),
    };
  });
  tenants.sort((a, b) => (b.usage ? b.usage.cost_usd_this_month : -1) - (a.usage ? a.usage.cost_usd_this_month : -1) || a.id - b.id);

  return {
    generated_at: new Date(now).toISOString(),
    month: bounds,
    totals: {
      tenants_by_status: tenantsByStatus,
      tenants_matching: Number(matching.n),
      tenants_returned: tenants.length,
      truncated: Number(matching.n) > tenants.length,
      events_this_month: totalEvents,
      cost_usd_this_month: totalCost,
    },
    tenants,
  };
}

module.exports = { buildOverview, parseOptions, OverviewInputError, DEFAULT_LIMIT, MAX_LIMIT };
